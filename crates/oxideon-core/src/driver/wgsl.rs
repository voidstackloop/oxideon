//! WebGPU Shading Language (WGSL) JIT Compute Pipeline Generator.
//!
//! Generates optimized, high-throughput WGSL compute shaders for fused transformer kernels
//! (Fused RMSNorm, Fused SwiGLU, 2D Tiled Matrix Multiply, Online-Softmax FlashAttention,
//! Rotary Position Embeddings, and 4-bit Quantized Affine Matrix-Vector Multiply).

/// WGSL JIT Kernel Generator for browser and desktop GPU acceleration via WebGPU.
#[derive(Debug, Clone)]
pub struct WgslKernelBuilder {
    pub entry_point: String,
    pub workgroup_size: (usize, usize, usize),
}

impl WgslKernelBuilder {
    /// Creates a new WGSL kernel builder.
    pub fn new(entry_point: impl Into<String>, workgroup_x: usize) -> Self {
        Self {
            entry_point: entry_point.into(),
            workgroup_size: (workgroup_x, 1, 1),
        }
    }

    /// Emits a fused RMSNorm compute shader in valid WGSL:
    /// $$y_i = \frac{x_i}{\sqrt{\frac{1}{d} \sum x_j^2 + \epsilon}} \cdot w_i$$
    pub fn emit_fused_rmsnorm_wgsl(&self, d_model: usize, eps: f32) -> String {
        let entry = &self.entry_point;
        let wx = self.workgroup_size.0;

        format!(
            r#"// Auto-generated by Oxideon WGSL JIT Compiler
@group(0) @binding(0) var<storage, read> input_x : array<f32>;
@group(0) @binding(1) var<storage, read> weight_w : array<f32>;
@group(0) @binding(2) var<storage, read_write> output_y : array<f32>;

var<workgroup> sdata : array<f32, {wx}>;

@compute @workgroup_size({wx}, 1, 1)
fn {entry}(
    @builtin(global_invocation_id) global_id : vec3<u32>,
    @builtin(local_invocation_id) local_id : vec3<u32>,
    @builtin(workgroup_id) workgroup_id : vec3<u32>
) {{
    let row = workgroup_id.x;
    let tid = local_id.x;
    let row_offset = row * {d_model}u;
    if (row_offset >= arrayLength(&input_x)) {{
        return;
    }}

    // 1. Thread-local sum of squares
    var sum_sq : f32 = 0.0;
    var i = tid;
    while (i < {d_model}u) {{
        let val = input_x[row_offset + i];
        sum_sq = sum_sq + val * val;
        i = i + {wx}u;
    }}
    sdata[tid] = sum_sq;
    workgroupBarrier();

    // 2. Workgroup tree reduction (strided form: correct for non-power-of-2
    // workgroup sizes, where halving skips partial sums).
    var s = 1u;
    while (s < {wx}u) {{
        if ((tid % (2u * s)) == 0u && (tid + s) < {wx}u) {{
            sdata[tid] = sdata[tid] + sdata[tid + s];
        }}
        workgroupBarrier();
        s = s * 2u;
    }}

    let mean_sq = sdata[0] / f32({d_model});
    let inv_rms = inverseSqrt(mean_sq + {eps:e});

    // 3. Normalization and affine scaling
    var j = tid;
    while (j < {d_model}u) {{
        let idx = row_offset + j;
        output_y[idx] = (input_x[idx] * inv_rms) * weight_w[j];
        j = j + {wx}u;
    }}
}}
"#
        )
    }

    /// Emits a fused SwiGLU compute shader in valid WGSL:
    /// $$y_i = \operatorname{silu}(a_i) \cdot b_i = \left(\frac{a_i}{1 + e^{-a_i}}\right) \cdot b_i$$
    pub fn emit_fused_swiglu_wgsl(&self) -> String {
        let entry = &self.entry_point;
        let wx = self.workgroup_size.0;

        format!(
            r#"// Auto-generated by Oxideon WGSL JIT Compiler
@group(0) @binding(0) var<storage, read> gate_a : array<f32>;
@group(0) @binding(1) var<storage, read> up_b : array<f32>;
@group(0) @binding(2) var<storage, read_write> output_y : array<f32>;

@compute @workgroup_size({wx}, 1, 1)
fn {entry}(@builtin(global_invocation_id) global_id : vec3<u32>) {{
    let idx = global_id.x;
    if (idx >= arrayLength(&gate_a)) {{
        return;
    }}
    let a = gate_a[idx];
    let b = up_b[idx];
    let silu_a = a / (1.0 + exp(-a));
    output_y[idx] = silu_a * b;
}}
"#
        )
    }

    /// Emits a 2D workgroup-tiled matrix multiplication compute shader in valid WGSL.
    pub fn emit_tiled_matmul_wgsl(&self, tile_dim: usize) -> String {
        let entry = &self.entry_point;
        let td = tile_dim.max(4);
        let td_sq = td * td;

        format!(
            r#"// Auto-generated by Oxideon WGSL JIT Compiler (2D Workgroup Tiled GEMM)
struct Dimensions {{
    M : u32,
    N : u32,
    K : u32,
}};

@group(0) @binding(0) var<storage, read> A : array<f32>;
@group(0) @binding(1) var<storage, read> B : array<f32>;
@group(0) @binding(2) var<storage, read_write> C : array<f32>;
@group(0) @binding(3) var<uniform> dims : Dimensions;

var<workgroup> tileA : array<f32, {td_sq}>;
var<workgroup> tileB : array<f32, {td_sq}>;

@compute @workgroup_size({td}, {td}, 1)
fn {entry}(
    @builtin(global_invocation_id) global_id : vec3<u32>,
    @builtin(local_invocation_id) local_id : vec3<u32>
) {{
    let row = global_id.y;
    let col = global_id.x;
    let lr = local_id.y;
    let lc = local_id.x;

    var acc : f32 = 0.0;
    let num_tiles = (dims.K + {td}u - 1u) / {td}u;

    for (var t : u32 = 0u; t < num_tiles; t = t + 1u) {{
        let k_a = t * {td}u + lc;
        if (row < dims.M && k_a < dims.K) {{
            tileA[lr * {td}u + lc] = A[row * dims.K + k_a];
        }} else {{
            tileA[lr * {td}u + lc] = 0.0;
        }}

        let k_b = t * {td}u + lr;
        if (col < dims.N && k_b < dims.K) {{
            tileB[lr * {td}u + lc] = B[k_b * dims.N + col];
        }} else {{
            tileB[lr * {td}u + lc] = 0.0;
        }}

        workgroupBarrier();

        for (var k : u32 = 0u; k < {td}u; k = k + 1u) {{
            acc = acc + tileA[lr * {td}u + k] * tileB[k * {td}u + lc];
        }}

        workgroupBarrier();
    }}

    if (row < dims.M && col < dims.N) {{
        C[row * dims.N + col] = acc;
    }}
}}
"#
        )
    }

    /// Emits an online-softmax FlashAttention compute shader in valid WGSL.
    pub fn emit_flash_attention_wgsl(
        &self,
        head_dim: usize,
        block_size: usize,
        is_causal: bool,
    ) -> String {
        let entry = &self.entry_point;
        let d = head_dim.max(2);
        let bs = block_size.max(4);
        let smem_elems = bs * d;
        let scale = 1.0f32 / (d as f32).sqrt();
        let causal_lit = if is_causal { "true" } else { "false" };

        format!(
            r#"// Auto-generated by Oxideon WGSL JIT Compiler (Online-Softmax FlashAttention)
@group(0) @binding(0) var<storage, read> Q : array<f32>;
@group(0) @binding(1) var<storage, read> K : array<f32>;
@group(0) @binding(2) var<storage, read> V : array<f32>;
@group(0) @binding(3) var<storage, read_write> O : array<f32>;

var<workgroup> shared_K : array<f32, {smem_elems}>;
var<workgroup> shared_V : array<f32, {smem_elems}>;

@compute @workgroup_size({bs}, 1, 1)
fn {entry}(
    @builtin(global_invocation_id) global_id : vec3<u32>,
    @builtin(local_invocation_id) local_id : vec3<u32>
) {{
    let q_idx = global_id.x;
    let tid = local_id.x;
    let seq_len = arrayLength(&Q) / {d}u;
    let is_causal : bool = {causal_lit};

    var row_max : f32 = -1e30;
    var row_sum : f32 = 0.0;
    var acc_o : array<f32, {d}>;
    for (var d_i : u32 = 0u; d_i < {d}u; d_i = d_i + 1u) {{
        acc_o[d_i] = 0.0;
    }}

    let num_blocks = (seq_len + {bs}u - 1u) / {bs}u;
    for (var blk : u32 = 0u; blk < num_blocks; blk = blk + 1u) {{
        let k_row = blk * {bs}u + tid;
        for (var d_i : u32 = 0u; d_i < {d}u; d_i = d_i + 1u) {{
            if (k_row < seq_len) {{
                shared_K[tid * {d}u + d_i] = K[k_row * {d}u + d_i];
                shared_V[tid * {d}u + d_i] = V[k_row * {d}u + d_i];
            }} else {{
                shared_K[tid * {d}u + d_i] = 0.0;
                shared_V[tid * {d}u + d_i] = 0.0;
            }}
        }}
        workgroupBarrier();

        for (var j : u32 = 0u; j < {bs}u; j = j + 1u) {{
            let k_idx = blk * {bs}u + j;
            if (k_idx < seq_len && (!is_causal || q_idx >= k_idx) && q_idx < seq_len) {{
                var dot_qk : f32 = 0.0;
                for (var d_i : u32 = 0u; d_i < {d}u; d_i = d_i + 1u) {{
                    dot_qk = dot_qk + Q[q_idx * {d}u + d_i] * shared_K[j * {d}u + d_i];
                }}
                let score = dot_qk * {scale:.8};
                let new_max = max(row_max, score);
                let exp_old = exp(row_max - new_max);
                let exp_new = exp(score - new_max);
                row_sum = row_sum * exp_old + exp_new;
                for (var d_i : u32 = 0u; d_i < {d}u; d_i = d_i + 1u) {{
                    acc_o[d_i] = acc_o[d_i] * exp_old + exp_new * shared_V[j * {d}u + d_i];
                }}
                row_max = new_max;
            }}
        }}
        workgroupBarrier();
    }}

    if (q_idx < seq_len) {{
        let inv_sum = 1.0 / max(row_sum, 1e-12);
        for (var d_i : u32 = 0u; d_i < {d}u; d_i = d_i + 1u) {{
            O[q_idx * {d}u + d_i] = acc_o[d_i] * inv_sum;
        }}
    }}
}}
"#
        )
    }

    /// Emits a Rotary Position Embedding (RoPE) compute shader in valid WGSL.
    pub fn emit_rope_wgsl(&self, head_dim: usize) -> String {
        let entry = &self.entry_point;
        let wx = self.workgroup_size.0;
        let d = head_dim.max(2);
        let half_d = d / 2;

        format!(
            r#"// Auto-generated by Oxideon WGSL JIT Compiler (Rotary Position Embedding)
@group(0) @binding(0) var<storage, read> input_x : array<f32>;
@group(0) @binding(1) var<storage, read_write> output_y : array<f32>;

@compute @workgroup_size({wx}, 1, 1)
fn {entry}(@builtin(global_invocation_id) global_id : vec3<u32>) {{
    let pair_idx = global_id.x;
    if (2u * pair_idx + 1u >= arrayLength(&input_x)) {{
        return;
    }}
    let pair_in_head = pair_idx % {half_d}u;
    let token_pos = pair_idx / {half_d}u;
    let freq_exp = f32(2u * pair_in_head) / f32({d}u);
    let angle = f32(token_pos) / pow(10000.0, freq_exp);
    let c = cos(angle);
    let s = sin(angle);

    let x0 = input_x[2u * pair_idx];
    let x1 = input_x[2u * pair_idx + 1u];
    output_y[2u * pair_idx] = x0 * c - x1 * s;
    output_y[2u * pair_idx + 1u] = x0 * s + x1 * c;
}}
"#
        )
    }

    /// Emits a 4-bit packed quantized affine matrix-vector multiplication (`Q4 GEMV`) shader in valid WGSL.
    pub fn emit_q4_gemv_wgsl(&self, group_size: usize) -> String {
        let entry = &self.entry_point;
        let wx = self.workgroup_size.0;
        let gs = group_size.max(8);
        let words_per_group = gs / 8;

        format!(
            r#"// Auto-generated by Oxideon WGSL JIT Compiler (4-bit Quantized Affine GEMV)
@group(0) @binding(0) var<storage, read> input_x : array<f32>;
@group(0) @binding(1) var<storage, read> w_packed_u32 : array<u32>;
@group(0) @binding(2) var<storage, read> scales : array<f32>;
@group(0) @binding(3) var<storage, read> biases : array<f32>;
@group(0) @binding(4) var<storage, read_write> output_y : array<f32>;

@compute @workgroup_size({wx}, 1, 1)
fn {entry}(@builtin(global_invocation_id) global_id : vec3<u32>) {{
    let row = global_id.x;
    if (row >= arrayLength(&output_y)) {{
        return;
    }}
    let in_features = arrayLength(&input_x);
    let num_groups = in_features / {gs}u;
    var acc : f32 = 0.0;

    for (var g : u32 = 0u; g < num_groups; g = g + 1u) {{
        let scale = scales[row * num_groups + g];
        let bias = biases[row * num_groups + g];
        let word_base = (row * num_groups + g) * {words_per_group}u;
        let x_base = g * {gs}u;

        for (var w : u32 = 0u; w < {words_per_group}u; w = w + 1u) {{
            let packed = w_packed_u32[word_base + w];
            for (var nib : u32 = 0u; nib < 8u; nib = nib + 1u) {{
                let q = f32((packed >> (nib * 4u)) & 0xFu);
                let w_val = scale * q + bias;
                acc = acc + input_x[x_base + w * 8u + nib] * w_val;
            }}
        }}
    }}
    output_y[row] = acc;
}}
"#
        )
    }
}

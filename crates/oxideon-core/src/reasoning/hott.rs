//! Homotopy Type Theory (HoTT), Univalence Axiom Transport & Higher Inductive Circle $\mathbb{S}^1$ Loop Spaces (Voevodsky, 2013).
//!
//! ### 1. Martin-Löf Identity Types $\mathrm{Id}_A(x, y)$ as Path Spaces
//! In Homotopy Type Theory, types $A$ are interpreted as $\infty$-groupoids (spaces), terms $x, y: A$ as points,
//! and identity proofs $p: x =_A y$ as continuous paths. Path groupoid operations satisfy:
//! • **Reflexivity**: $\mathrm{refl}_x : x =_A x$
//! • **Path Inversion**: $p^{-1} : y =_A x$
//! • **Path Concatenation**: $p \cdot q : x =_A z$
//!
//! ### 2. Higher Inductive Circle $\mathbb{S}^1$ & Encode-Decode Theorem ($\pi_1(\mathbb{S}^1) \cong \mathbb{Z}$)
//! The circle $\mathbb{S}^1$ is generated by a base point $\mathsf{base} : \mathbb{S}^1$ and a non-trivial path
//! $\mathsf{loop} : \mathsf{base} =_{\mathbb{S}^1} \mathsf{base}$.
//! By Voevodsky's **Univalence Axiom** $(A \simeq B) \simeq (A =_{\mathcal{U}} B)$, the universal cover family
//! $\mathsf{Code} : \mathbb{S}^1 \to \mathcal{U}$ maps $\mathsf{base} \mapsto \mathbb{Z}$ and
//! $\mathsf{loop} \mapsto \mathsf{ua}(\mathsf{succ})$, proving constructively that $\Omega(\mathbb{S}^1, \mathsf{base}) \simeq \mathbb{Z}$.

use crate::error::Result;

/// Homotopy Type Theory (HoTT) Univalent Transport & $\pi_1(\mathbb{S}^1)$ Loop Space Engine.
#[derive(Debug, Clone, Default)]
pub struct HomotopyTypeEngine;

impl HomotopyTypeEngine {
    /// Creates a new Homotopy Type Theory engine.
    pub fn new() -> Self {
        Self
    }

    /// Executes the HoTT `encode : (base =_{S^1} base) -> Z` functor by transporting $0 \in \mathbb{Z}$
    /// along a word of loop generators (`+1` for $\mathsf{loop}$, `-1` for $\mathsf{loop}^{-1}$, `0` for $\mathsf{refl}$).
    pub fn encode_circle_loop(loop_word: &[i32]) -> i64 {
        let mut winding_number = 0_i64;
        for &step in loop_word {
            winding_number += step.signum() as i64;
        }
        winding_number
    }

    /// Executes the HoTT `decode : Z -> (base =_{S^1} base)` functor producing the canonical reduced loop word $\mathsf{loop}^n$.
    /// The word has `|n|` letters, so `|n|` is limited to [`MAX_ITERATIONS`](crate::limits::MAX_ITERATIONS).
    pub fn decode_winding_number(n: i64) -> Result<Vec<i32>> {
        let count = crate::limits::check_iterations(
            "|n|",
            usize::try_from(n.unsigned_abs()).unwrap_or(usize::MAX),
        )?;
        let step_gen = if n >= 0 { 1 } else { -1 };
        crate::layout::try_filled(count, step_gen)
    }

    /// Verifies the HoTT groupoid laws and Encode-Decode isomorphism $\mathrm{encode}(\mathrm{decode}(n)) = n$.
    pub fn verify_univalent_circle_coherence(n: i64) -> Result<bool> {
        let word = Self::decode_winding_number(n)?;
        let encoded = Self::encode_circle_loop(&word);
        if encoded != n {
            return Ok(false);
        }
        // Verify path inverse p . p^{-1} = refl (winding 0)
        let mut inv_word: Vec<i32> = word.iter().rev().map(|&g| -g).collect();
        let mut concat = word;
        concat.append(&mut inv_word);
        Ok(Self::encode_circle_loop(&concat) == 0)
    }

    /// Transports a feature vector $v \in \mathbb{R}^d$ along an orthogonal equivalence $Q \in O(d)$ induced by Univalence.
    pub fn univalent_orthogonal_transport(v: &[f64], theta_rad: f64) -> Result<Vec<f64>> {
        let mut out = v.to_vec();
        let c = theta_rad.cos();
        let s = theta_rad.sin();
        for pair in out.chunks_exact_mut(2) {
            let x = pair[0];
            let y = pair[1];
            pair[0] = c * x - s * y;
            pair[1] = s * x + c * y;
        }
        Ok(out)
    }
}

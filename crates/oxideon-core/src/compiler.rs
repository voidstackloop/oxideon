//! Symbolic SSA Intermediate Representation (`IrGraph`) and optimizing compiler passes:
//! - **Algebraic Simplification** (`x + 0 -> x`, `x * 1 -> x`, `x * 0 -> 0`, `exp(ln(x)) -> x`, `t(t(x)) -> x`)
//! - **Common Subexpression Elimination (`CSE`)** (deduplicating identical pure operations)
//! - **Operator Fusion** (`matmul + add -> FusedLinear`, `FusedLinear + relu/silu/gelu`, `mul + add -> FusedFma`)
//! - **Dead Code Elimination (`DCE`)** (pruning unreachable SSA instructions)
//! - **Executable Runtime (`IrGraph::execute`)**

pub mod aot;
pub mod symbolic_shape;

pub use aot::{AotCompiler, AotTarget};
pub use symbolic_shape::{SymDim, SymbolicShape};

use std::collections::{HashMap, HashSet};

use crate::error::{Error, Result};
use crate::tensor::{Tensor, enable_grad};

pub type ValueId = usize;

/// Symbolic SSA operations in [`IrGraph`].
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub enum IrOp {
    Input {
        index: usize,
    },
    ZeroLike {
        src: ValueId,
    },
    OneLike {
        src: ValueId,
    },
    Add(ValueId, ValueId),
    Sub(ValueId, ValueId),
    Mul(ValueId, ValueId),
    Div(ValueId, ValueId),
    Matmul(ValueId, ValueId),
    Transpose2D(ValueId),
    Relu(ValueId),
    Silu(ValueId),
    Gelu(ValueId),
    Tanh(ValueId),
    Exp(ValueId),
    Ln(ValueId),
    Neg(ValueId),
    Square(ValueId),
    SumAll(ValueId),
    MeanAll(ValueId),
    // Fused composite kernels generated by the fusion pass:
    /// Fused `a * b + c` (Fused Multiply-Add).
    FusedFma(ValueId, ValueId, ValueId),
    /// Fused `x @ w + b`.
    FusedLinear {
        x: ValueId,
        w: ValueId,
        b: ValueId,
    },
    /// Fused `relu(x @ w + b)`.
    FusedLinearRelu {
        x: ValueId,
        w: ValueId,
        b: ValueId,
    },
    /// Fused `silu(x @ w + b)`.
    FusedLinearSilu {
        x: ValueId,
        w: ValueId,
        b: ValueId,
    },
    /// Fused `gelu(x @ w + b)`.
    FusedLinearGelu {
        x: ValueId,
        w: ValueId,
        b: ValueId,
    },
}

impl IrOp {
    /// Returns all operand [`ValueId`]s read by this instruction.
    pub fn operands(&self) -> Vec<ValueId> {
        match *self {
            Self::Input { .. } => vec![],
            Self::ZeroLike { src }
            | Self::OneLike { src }
            | Self::Transpose2D(src)
            | Self::Relu(src)
            | Self::Silu(src)
            | Self::Gelu(src)
            | Self::Tanh(src)
            | Self::Exp(src)
            | Self::Ln(src)
            | Self::Neg(src)
            | Self::Square(src)
            | Self::SumAll(src)
            | Self::MeanAll(src) => vec![src],
            Self::Add(a, b)
            | Self::Sub(a, b)
            | Self::Mul(a, b)
            | Self::Div(a, b)
            | Self::Matmul(a, b) => vec![a, b],
            Self::FusedFma(a, b, c) => vec![a, b, c],
            Self::FusedLinear { x, w, b }
            | Self::FusedLinearRelu { x, w, b }
            | Self::FusedLinearSilu { x, w, b }
            | Self::FusedLinearGelu { x, w, b } => vec![x, w, b],
        }
    }

    pub fn is_fused(&self) -> bool {
        matches!(
            self,
            Self::FusedFma(..)
                | Self::FusedLinear { .. }
                | Self::FusedLinearRelu { .. }
                | Self::FusedLinearSilu { .. }
                | Self::FusedLinearGelu { .. }
        )
    }
}

#[derive(Debug, Clone)]
pub struct IrNode {
    pub id: ValueId,
    pub op: IrOp,
}

/// Static Single Assignment (SSA) computation graph with optimizing compiler passes.
#[derive(Debug, Clone, Default)]
pub struct IrGraph {
    pub nodes: Vec<IrNode>,
    pub outputs: Vec<ValueId>,
    pub num_inputs: usize,
}

/// Summary statistics before and after running [`IrGraph::optimize`].
#[derive(Debug, Clone, Copy)]
pub struct OptimizationReport {
    pub nodes_before: usize,
    pub nodes_after: usize,
    pub fused_ops_count: usize,
}

impl IrGraph {
    /// Exports this SSA [`IrGraph`] to an ONNX `ModelProto` byte buffer.
    pub fn to_onnx(&self, input_shapes: &[Vec<usize>], model_name: &str) -> Result<Vec<u8>> {
        crate::serialize::onnx::export_ir_graph(self, input_shapes, model_name)
    }

    pub fn new() -> Self {
        Self::default()
    }

    pub fn add_input(&mut self) -> ValueId {
        let idx = self.num_inputs;
        self.num_inputs += 1;
        self.push_op(IrOp::Input { index: idx })
    }

    pub fn push_op(&mut self, op: IrOp) -> ValueId {
        let id = self.nodes.len();
        self.nodes.push(IrNode { id, op });
        id
    }

    pub fn set_outputs(&mut self, outputs: Vec<ValueId>) {
        self.outputs = outputs;
    }

    /// Validates graph integrity (node ids match positions, every operand and
    /// output id is in range, input indices are below `num_inputs`). Graphs
    /// built via [`IrGraph::push_op`] always pass; hand-built graphs (the
    /// fields are `pub`) must be validated before optimizing or executing.
    pub fn validate(&self) -> Result<()> {
        for (i, node) in self.nodes.iter().enumerate() {
            if node.id != i {
                return Err(Error::Msg(format!(
                    "IrGraph: node id {} does not match position {i}",
                    node.id
                )));
            }
            for op_id in node.op.operands() {
                if op_id >= self.nodes.len() {
                    return Err(Error::Msg(format!(
                        "IrGraph: node {i} references out-of-range id {op_id}"
                    )));
                }
            }
            if let IrOp::Input { index } = node.op
                && index >= self.num_inputs
            {
                return Err(Error::Msg(format!(
                    "IrGraph: input index {index} exceeds num_inputs {}",
                    self.num_inputs
                )));
            }
        }
        for &o in &self.outputs {
            if o >= self.nodes.len() {
                return Err(Error::Msg(format!(
                    "IrGraph: output id {o} out of range ({} nodes)",
                    self.nodes.len()
                )));
            }
        }
        Ok(())
    }

    pub fn active_node_count(&self) -> usize {
        self.live_set().len()
    }

    pub fn fused_op_count(&self) -> usize {
        let live = self.live_set();
        self.nodes
            .iter()
            .filter(|n| live.contains(&n.id) && n.op.is_fused())
            .count()
    }

    /// Runs the full optimization pipeline:
    /// 1. Algebraic simplification (`x + 0 -> x`, `x * 1 -> x`, `exp(ln(x)) -> x`, `t(t(x)) -> x`)
    /// 2. Common Subexpression Elimination (`CSE`)
    /// 3. Operator Fusion (`matmul + add -> FusedLinear`, `FusedLinear + activation`, `mul + add -> FusedFma`)
    /// 4. Dead Code Elimination (`DCE`)
    pub fn optimize(&mut self) -> Result<OptimizationReport> {
        self.validate()?;
        let nodes_before = self.active_node_count();
        self.simplify_algebraic()?;
        self.eliminate_common_subexpressions()?;
        self.fuse_operators()?;
        self.eliminate_dead_code()?;
        let nodes_after = self.nodes.len();
        let fused_ops_count = self.nodes.iter().filter(|n| n.op.is_fused()).count();
        Ok(OptimizationReport {
            nodes_before,
            nodes_after,
            fused_ops_count,
        })
    }

    /// Pass 1: Algebraic identity simplification.
    pub fn simplify_algebraic(&mut self) -> Result<()> {
        self.validate()?;
        let mut alias: HashMap<ValueId, ValueId> = HashMap::new();
        let resolve = |id: ValueId, map: &HashMap<ValueId, ValueId>| -> ValueId {
            let mut cur = id;
            while let Some(&next) = map.get(&cur) {
                if next == cur {
                    break;
                }
                cur = next;
            }
            cur
        };

        for i in 0..self.nodes.len() {
            let op = remap_op(&self.nodes[i].op, |v| resolve(v, &alias));
            self.nodes[i].op = op.clone();

            match op {
                // x + 0 -> x, 0 + x -> x. Sound only when the zero is shaped
                // exactly like the surviving operand: under broadcasting the
                // output shape can differ from both inputs, and the IR carries
                // no shapes to check. `ZeroLike{src} == operand` guarantees it.
                IrOp::Add(a, b) => {
                    if matches!(self.nodes[b].op, IrOp::ZeroLike { src } if src == a) {
                        alias.insert(i, a);
                    } else if matches!(self.nodes[a].op, IrOp::ZeroLike { src } if src == b) {
                        alias.insert(i, b);
                    }
                }
                // x - 0 -> x, x - x -> 0
                IrOp::Sub(a, b) => {
                    if matches!(self.nodes[b].op, IrOp::ZeroLike { src } if src == a) {
                        alias.insert(i, a);
                    } else if a == b {
                        self.nodes[i].op = IrOp::ZeroLike { src: a };
                    }
                }
                // x * 1 -> x, 1 * x -> x, x * 0 -> 0 (same broadcast caveat).
                IrOp::Mul(a, b) => {
                    if matches!(self.nodes[b].op, IrOp::OneLike { src } if src == a)
                        || matches!(self.nodes[a].op, IrOp::ZeroLike { src } if src == b)
                    {
                        alias.insert(i, a);
                    } else if matches!(self.nodes[a].op, IrOp::OneLike { src } if src == b)
                        || matches!(self.nodes[b].op, IrOp::ZeroLike { src } if src == a)
                    {
                        alias.insert(i, b);
                    }
                }
                // transpose(transpose(x)) -> x
                IrOp::Transpose2D(a) => {
                    if let IrOp::Transpose2D(orig) = self.nodes[a].op {
                        alias.insert(i, resolve(orig, &alias));
                    }
                }
                // neg(neg(x)) -> x
                IrOp::Neg(a) => {
                    if let IrOp::Neg(orig) = self.nodes[a].op {
                        alias.insert(i, resolve(orig, &alias));
                    }
                }
                // exp(ln(x)) -> x
                IrOp::Exp(a) => {
                    if let IrOp::Ln(orig) = self.nodes[a].op {
                        alias.insert(i, resolve(orig, &alias));
                    }
                }
                // ln(exp(x)) -> x
                IrOp::Ln(a) => {
                    if let IrOp::Exp(orig) = self.nodes[a].op {
                        alias.insert(i, resolve(orig, &alias));
                    }
                }
                _ => {}
            }
        }

        for n in &mut self.nodes {
            n.op = remap_op(&n.op, |v| resolve(v, &alias));
        }
        for out in &mut self.outputs {
            *out = resolve(*out, &alias);
        }
        Ok(())
    }

    /// Pass 2: Common Subexpression Elimination (`CSE`).
    pub fn eliminate_common_subexpressions(&mut self) -> Result<()> {
        self.validate()?;
        let mut seen: HashMap<IrOp, ValueId> = HashMap::new();
        let mut alias: HashMap<ValueId, ValueId> = HashMap::new();
        let resolve = |id: ValueId, map: &HashMap<ValueId, ValueId>| -> ValueId {
            let mut cur = id;
            while let Some(&next) = map.get(&cur) {
                if next == cur {
                    break;
                }
                cur = next;
            }
            cur
        };

        for i in 0..self.nodes.len() {
            let mut op = remap_op(&self.nodes[i].op, |v| resolve(v, &alias));
            // Canonicalize commutative binary ops (Add, Mul) by ordering operands
            match &mut op {
                IrOp::Add(a, b) | IrOp::Mul(a, b) if *a > *b => {
                    std::mem::swap(a, b);
                }
                _ => {}
            }
            self.nodes[i].op = op.clone();
            if let Some(&existing) = seen.get(&op) {
                alias.insert(i, existing);
            } else {
                seen.insert(op, i);
            }
        }

        for n in &mut self.nodes {
            n.op = remap_op(&n.op, |v| resolve(v, &alias));
        }
        for out in &mut self.outputs {
            *out = resolve(*out, &alias);
        }
        Ok(())
    }

    /// Pass 3: Operator Fusion (`Matmul + Add -> FusedLinear`, `FusedLinear + Activation`, `Mul + Add -> FusedFma`).
    pub fn fuse_operators(&mut self) -> Result<()> {
        self.validate()?;
        for i in 0..self.nodes.len() {
            let op = self.nodes[i].op.clone();
            match op {
                IrOp::Add(lhs, rhs) => {
                    if let IrOp::Matmul(x, w) = self.nodes[lhs].op {
                        self.nodes[i].op = IrOp::FusedLinear { x, w, b: rhs };
                    } else if let IrOp::Matmul(x, w) = self.nodes[rhs].op {
                        self.nodes[i].op = IrOp::FusedLinear { x, w, b: lhs };
                    } else if let IrOp::Mul(a, b) = self.nodes[lhs].op {
                        self.nodes[i].op = IrOp::FusedFma(a, b, rhs);
                    } else if let IrOp::Mul(a, b) = self.nodes[rhs].op {
                        self.nodes[i].op = IrOp::FusedFma(a, b, lhs);
                    }
                }
                IrOp::Relu(src) => {
                    if let IrOp::FusedLinear { x, w, b } = self.nodes[src].op {
                        self.nodes[i].op = IrOp::FusedLinearRelu { x, w, b };
                    }
                }
                IrOp::Silu(src) => {
                    if let IrOp::FusedLinear { x, w, b } = self.nodes[src].op {
                        self.nodes[i].op = IrOp::FusedLinearSilu { x, w, b };
                    }
                }
                IrOp::Gelu(src) => {
                    if let IrOp::FusedLinear { x, w, b } = self.nodes[src].op {
                        self.nodes[i].op = IrOp::FusedLinearGelu { x, w, b };
                    }
                }
                _ => {}
            }
        }
        Ok(())
    }

    /// Pass 4: Dead Code Elimination (`DCE`) compacting the SSA graph to only live nodes.
    pub fn eliminate_dead_code(&mut self) -> Result<()> {
        self.validate()?;
        let live = self.live_set();
        let mut new_nodes = Vec::with_capacity(live.len());
        let mut old_to_new: HashMap<ValueId, ValueId> = HashMap::new();

        for node in &self.nodes {
            if live.contains(&node.id) {
                let new_id = new_nodes.len();
                old_to_new.insert(node.id, new_id);
                let mut missing: Option<ValueId> = None;
                let remapped_op = remap_op(&node.op, |v| match old_to_new.get(&v) {
                    Some(&id) => id,
                    None => {
                        missing = Some(v);
                        0
                    }
                });
                if let Some(v) = missing {
                    return Err(Error::Msg(format!(
                        "IrGraph::eliminate_dead_code: node {} references {v}, which is not defined above it (graph not topological)",
                        node.id
                    )));
                }
                new_nodes.push(IrNode {
                    id: new_id,
                    op: remapped_op,
                });
            }
        }
        self.nodes = new_nodes;
        self.outputs = self.outputs.iter().map(|v| old_to_new[v]).collect();
        Ok(())
    }

    fn live_set(&self) -> HashSet<ValueId> {
        // Defensive: out-of-range ids (only possible in an unvalidated
        // hand-built graph) are skipped instead of panicking; the fallible
        // passes and `validate` reject such graphs strictly.
        let mut live = HashSet::new();
        let mut stack = self.outputs.clone();
        while let Some(id) = stack.pop() {
            if id < self.nodes.len() && live.insert(id) {
                for op_id in self.nodes[id].op.operands() {
                    stack.push(op_id);
                }
            }
        }
        live
    }

    /// Executes the (optionally optimized/fused) [`IrGraph`] on runtime [`Tensor`] `inputs`.
    pub fn execute(&self, inputs: &[Tensor]) -> Result<Vec<Tensor>> {
        self.validate()?;
        if inputs.len() < self.num_inputs {
            return Err(Error::Msg(format!(
                "IrGraph expected {} inputs, got {}",
                self.num_inputs,
                inputs.len()
            )));
        }
        let mut vals: Vec<Option<Tensor>> = vec![None; self.nodes.len()];
        let live = self.live_set();

        for node in &self.nodes {
            if !live.contains(&node.id) {
                continue;
            }
            let get = |id: ValueId, vals: &[Option<Tensor>]| -> Result<Tensor> {
                vals.get(id)
                    .and_then(|v| v.clone())
                    .ok_or_else(|| {
                        Error::Msg(format!(
                            "IrGraph::execute: operand {id} of node {} not computed (graph not topological)",
                            node.id
                        ))
                    })
            };
            let t = match node.op {
                IrOp::Input { index } => inputs
                    .get(index)
                    .ok_or_else(|| {
                        Error::Msg(format!(
                            "IrGraph::execute: input index {index} out of range ({} inputs)",
                            inputs.len()
                        ))
                    })?
                    .clone(),
                IrOp::ZeroLike { src } => get(src, &vals)?.zeros_like()?,
                IrOp::OneLike { src } => get(src, &vals)?.ones_like()?,
                IrOp::Add(a, b) => get(a, &vals)?.add(&get(b, &vals)?)?,
                IrOp::Sub(a, b) => get(a, &vals)?.sub(&get(b, &vals)?)?,
                IrOp::Mul(a, b) => get(a, &vals)?.mul(&get(b, &vals)?)?,
                IrOp::Div(a, b) => get(a, &vals)?.div(&get(b, &vals)?)?,
                IrOp::Matmul(a, b) => get(a, &vals)?.matmul(&get(b, &vals)?)?,
                IrOp::Transpose2D(a) => get(a, &vals)?.t()?,
                IrOp::Relu(a) => get(a, &vals)?.relu()?,
                IrOp::Silu(a) => get(a, &vals)?.silu()?,
                IrOp::Gelu(a) => get(a, &vals)?.gelu()?,
                IrOp::Tanh(a) => get(a, &vals)?.tanh()?,
                IrOp::Exp(a) => get(a, &vals)?.exp()?,
                IrOp::Ln(a) => get(a, &vals)?.ln()?,
                IrOp::Neg(a) => get(a, &vals)?.neg()?,
                IrOp::Square(a) => get(a, &vals)?.square()?,
                IrOp::SumAll(a) => get(a, &vals)?.sum()?,
                IrOp::MeanAll(a) => get(a, &vals)?.mean()?,
                IrOp::FusedFma(a, b, c) => {
                    get(a, &vals)?.mul(&get(b, &vals)?)?.add(&get(c, &vals)?)?
                }
                IrOp::FusedLinear { x, w, b } => get(x, &vals)?
                    .matmul(&get(w, &vals)?)?
                    .add(&get(b, &vals)?)?,
                IrOp::FusedLinearRelu { x, w, b } => get(x, &vals)?
                    .matmul(&get(w, &vals)?)?
                    .add(&get(b, &vals)?)?
                    .relu()?,
                IrOp::FusedLinearSilu { x, w, b } => get(x, &vals)?
                    .matmul(&get(w, &vals)?)?
                    .add(&get(b, &vals)?)?
                    .silu()?,
                IrOp::FusedLinearGelu { x, w, b } => get(x, &vals)?
                    .matmul(&get(w, &vals)?)?
                    .add(&get(b, &vals)?)?
                    .gelu()?,
            };
            vals[node.id] = Some(t);
        }

        let mut out = Vec::with_capacity(self.outputs.len());
        for &oid in &self.outputs {
            out.push(
                vals[oid]
                    .clone()
                    .ok_or_else(|| Error::Msg("missing output value in IrGraph::execute".into()))?,
            );
        }
        Ok(out)
    }

    /// Symbolic Reverse-Mode Automatic Differentiation on [`IrGraph`]:
    /// Appends the backward SSA instructions for `output` with respect to `wrt` directly
    /// into `self`, returning the gradient [`ValueId`] for each entry in `wrt`.
    /// Because gradients are emitted as first-class [`IrOp`] nodes, `self.optimize()` can
    /// simplify, CSE, fuse, and DCE the joint forward+backward graph (or differentiate again!).
    ///
    /// Fused linears are automatically unfused first, so optimized graphs
    /// differentiate. `Relu`/`Gelu` have no rule: their backward needs a
    /// comparison the IR cannot express (see the error message).
    pub fn differentiate(&mut self, output: ValueId, wrt: &[ValueId]) -> Result<Vec<ValueId>> {
        self.validate()?;
        let num_fwd = self.nodes.len();
        if output >= num_fwd {
            return Err(Error::Msg(format!(
                "IrGraph::differentiate: output ValueId {output} out of bounds ({num_fwd})"
            )));
        }
        let mut output = output;
        let mut wrt: Vec<ValueId> = wrt.to_vec();

        // Unfuse activation-fused linears into primitive pairs so graphs that
        // went through `optimize()` keep differentiating.
        for i in 0..num_fwd {
            enum Act {
                Relu,
                Silu,
                Gelu,
            }
            let fused = match self.nodes[i].op.clone() {
                IrOp::FusedLinearRelu { x, w, b } => Some((x, w, b, Act::Relu)),
                IrOp::FusedLinearSilu { x, w, b } => Some((x, w, b, Act::Silu)),
                IrOp::FusedLinearGelu { x, w, b } => Some((x, w, b, Act::Gelu)),
                _ => None,
            };
            let Some((x, w, b, act)) = fused else {
                continue;
            };
            let lin = self.push_op(IrOp::FusedLinear { x, w, b });
            let out = match act {
                Act::Relu => self.push_op(IrOp::Relu(lin)),
                Act::Silu => self.push_op(IrOp::Silu(lin)),
                Act::Gelu => self.push_op(IrOp::Gelu(lin)),
            };
            let remap = |v: ValueId| if v == i { out } else { v };
            for node in &mut self.nodes[..num_fwd] {
                node.op = remap_op(&node.op, remap);
            }
            if output == i {
                output = out;
            }
            for v in &mut wrt {
                if *v == i {
                    *v = out;
                }
            }
        }

        // Restore topological id order after unfusing: the appended
        // `FusedLinear`/activation pairs sit AFTER their consumers (forward
        // references), which `execute` rejects and `eliminate_dead_code` panics
        // on. Kahn's algorithm over the still-purely-forward graph, stable for
        // the acyclic case; leftover cyclic nodes (hand-built only) keep old-id
        // order so downstream passes report them instead of hanging.
        {
            let n = self.nodes.len();
            let mut indeg = vec![0usize; n];
            let mut users: Vec<Vec<ValueId>> = vec![Vec::new(); n];
            for (i, node) in self.nodes.iter().enumerate() {
                for dep in node.op.operands() {
                    users[dep].push(i);
                    indeg[i] += 1;
                }
            }
            let mut stack: Vec<ValueId> = (0..n).filter(|&i| indeg[i] == 0).collect();
            let mut order = Vec::with_capacity(n);
            while let Some(i) = stack.pop() {
                order.push(i);
                for &u in &users[i] {
                    indeg[u] -= 1;
                    if indeg[u] == 0 {
                        stack.push(u);
                    }
                }
            }
            if order.len() < n {
                let mut placed = vec![false; n];
                for &i in &order {
                    placed[i] = true;
                }
                order.extend((0..n).filter(|&i| !placed[i]));
            }
            let mut new_id = vec![0usize; n];
            for (new, &old) in order.iter().enumerate() {
                new_id[old] = new;
            }
            let mut sorted = Vec::with_capacity(n);
            for &old in &order {
                sorted.push(IrNode {
                    id: new_id[old],
                    op: remap_op(&self.nodes[old].op, |v| new_id[v]),
                });
            }
            self.nodes = sorted;
            output = new_id[output];
            for v in &mut wrt {
                *v = new_id[*v];
            }
            for o in &mut self.outputs {
                *o = new_id[*o];
            }
        }
        // Forward boundary AFTER unfusing: the backward sweep must also visit the
        // unfused `FusedLinear`/activation pairs; otherwise their gradients are
        // silently dropped and `wrt` entries collapse to `ZeroLike`. Nodes pushed
        // during the sweep itself (gradient values) stay above this boundary and
        // are never visited.
        let fwd_end = self.nodes.len();
        let mut grads: HashMap<ValueId, ValueId> = HashMap::new();
        let seed = self.push_op(IrOp::OneLike { src: output });
        grads.insert(output, seed);

        let acc_grad =
            |g: &mut Self, map: &mut HashMap<ValueId, ValueId>, v: ValueId, dv: ValueId| {
                if let Some(&existing) = map.get(&v) {
                    let sum = g.push_op(IrOp::Add(existing, dv));
                    map.insert(v, sum);
                } else {
                    map.insert(v, dv);
                }
            };

        // Consumers-first sweep order: unfused pairs are appended AFTER their
        // consumers, so raw id order is not a valid backward order (a single
        // reversed-id pass visits them before their gradients exist). Iterative
        // post-order DFS from `output`, swept in reverse, so every consumer is
        // processed before its producers. Terminates on hand-built cycles via
        // the `seen` set (cyclic graphs still fail loudly at `execute`).
        let mut post: Vec<ValueId> = Vec::new();
        {
            let mut seen = vec![false; fwd_end];
            let mut stack = vec![(output, false)];
            while let Some((id, expanded)) = stack.pop() {
                if id >= fwd_end || seen[id] {
                    continue;
                }
                if expanded {
                    seen[id] = true;
                    post.push(id);
                    continue;
                }
                stack.push((id, true));
                for dep in self.nodes[id].op.operands() {
                    if dep < fwd_end && !seen[dep] {
                        stack.push((dep, false));
                    }
                }
            }
        }
        for id in post.into_iter().rev() {
            let Some(&dout) = grads.get(&id) else {
                continue;
            };
            let op = self.nodes[id].op.clone();
            match op {
                IrOp::Input { .. } | IrOp::ZeroLike { .. } | IrOp::OneLike { .. } => {}
                IrOp::Add(a, b) => {
                    acc_grad(self, &mut grads, a, dout);
                    acc_grad(self, &mut grads, b, dout);
                }
                IrOp::Sub(a, b) => {
                    acc_grad(self, &mut grads, a, dout);
                    let neg_dout = self.push_op(IrOp::Neg(dout));
                    acc_grad(self, &mut grads, b, neg_dout);
                }
                IrOp::Mul(a, b) => {
                    let da = self.push_op(IrOp::Mul(dout, b));
                    let db = self.push_op(IrOp::Mul(dout, a));
                    acc_grad(self, &mut grads, a, da);
                    acc_grad(self, &mut grads, b, db);
                }
                IrOp::Div(a, b) => {
                    let da = self.push_op(IrOp::Div(dout, b));
                    let num = self.push_op(IrOp::Mul(dout, a));
                    let b_sq = self.push_op(IrOp::Square(b));
                    let quot = self.push_op(IrOp::Div(num, b_sq));
                    let db = self.push_op(IrOp::Neg(quot));
                    acc_grad(self, &mut grads, a, da);
                    acc_grad(self, &mut grads, b, db);
                }
                IrOp::Matmul(a, b) => {
                    let bt = self.push_op(IrOp::Transpose2D(b));
                    let da = self.push_op(IrOp::Matmul(dout, bt));
                    let at = self.push_op(IrOp::Transpose2D(a));
                    let db = self.push_op(IrOp::Matmul(at, dout));
                    acc_grad(self, &mut grads, a, da);
                    acc_grad(self, &mut grads, b, db);
                }
                IrOp::Transpose2D(a) => {
                    let da = self.push_op(IrOp::Transpose2D(dout));
                    acc_grad(self, &mut grads, a, da);
                }
                IrOp::Neg(a) => {
                    let da = self.push_op(IrOp::Neg(dout));
                    acc_grad(self, &mut grads, a, da);
                }
                IrOp::Exp(a) => {
                    let da = self.push_op(IrOp::Mul(dout, id));
                    acc_grad(self, &mut grads, a, da);
                }
                IrOp::Ln(a) => {
                    let da = self.push_op(IrOp::Div(dout, a));
                    acc_grad(self, &mut grads, a, da);
                }
                IrOp::Square(a) => {
                    let two_a = self.push_op(IrOp::Add(a, a));
                    let da = self.push_op(IrOp::Mul(dout, two_a));
                    acc_grad(self, &mut grads, a, da);
                }
                IrOp::Tanh(a) => {
                    let one = self.push_op(IrOp::OneLike { src: id });
                    let sq = self.push_op(IrOp::Square(id));
                    let dtanh = self.push_op(IrOp::Sub(one, sq));
                    let da = self.push_op(IrOp::Mul(dout, dtanh));
                    acc_grad(self, &mut grads, a, da);
                }
                IrOp::Silu(a) => {
                    // d/da silu(a) = sig(a) * (1 + a * (1 - sig(a)))
                    let one = self.push_op(IrOp::OneLike { src: a });
                    let neg_a = self.push_op(IrOp::Neg(a));
                    let exp_neg_a = self.push_op(IrOp::Exp(neg_a));
                    let denom = self.push_op(IrOp::Add(one, exp_neg_a));
                    let sig = self.push_op(IrOp::Div(one, denom));
                    let one_minus_sig = self.push_op(IrOp::Sub(one, sig));
                    let a_oms = self.push_op(IrOp::Mul(a, one_minus_sig));
                    let inner = self.push_op(IrOp::Add(one, a_oms));
                    let dsilu = self.push_op(IrOp::Mul(sig, inner));
                    let da = self.push_op(IrOp::Mul(dout, dsilu));
                    acc_grad(self, &mut grads, a, da);
                }
                IrOp::SumAll(a) => {
                    let ones = self.push_op(IrOp::OneLike { src: a });
                    let da = self.push_op(IrOp::Mul(ones, dout));
                    acc_grad(self, &mut grads, a, da);
                }
                IrOp::MeanAll(a) => {
                    // d/da mean(a) = dout / n, with n counted symbolically.
                    let ones = self.push_op(IrOp::OneLike { src: a });
                    let n = self.push_op(IrOp::SumAll(ones));
                    let scaled = self.push_op(IrOp::Div(dout, n));
                    let da = self.push_op(IrOp::Mul(ones, scaled));
                    acc_grad(self, &mut grads, a, da);
                }
                IrOp::FusedFma(a, b, c) => {
                    let da = self.push_op(IrOp::Mul(dout, b));
                    let db = self.push_op(IrOp::Mul(dout, a));
                    acc_grad(self, &mut grads, a, da);
                    acc_grad(self, &mut grads, b, db);
                    acc_grad(self, &mut grads, c, dout);
                }
                IrOp::FusedLinear { x, w, b } => {
                    let wt = self.push_op(IrOp::Transpose2D(w));
                    let dx = self.push_op(IrOp::Matmul(dout, wt));
                    let xt = self.push_op(IrOp::Transpose2D(x));
                    let dw = self.push_op(IrOp::Matmul(xt, dout));
                    acc_grad(self, &mut grads, x, dx);
                    acc_grad(self, &mut grads, w, dw);
                    acc_grad(self, &mut grads, b, dout);
                }
                IrOp::Relu(_) | IrOp::Gelu(_) => {
                    return Err(Error::Msg(
                        "IrGraph::differentiate: Relu/Gelu backward needs a comparison \
                         (step/erf) the IR cannot express; differentiate before fusing, \
                         or use tensor autograd"
                            .into(),
                    ));
                }
                other => {
                    return Err(Error::Msg(format!(
                        "IrGraph::differentiate: unsupported symbolic op {other:?}"
                    )));
                }
            }
        }

        let mut result = Vec::with_capacity(wrt.len());
        for &v in &wrt {
            if let Some(&gv) = grads.get(&v) {
                result.push(gv);
            } else {
                let z = self.push_op(IrOp::ZeroLike { src: v });
                result.push(z);
            }
        }
        Ok(result)
    }

    /// Computes a static Linear-Scan Buffer Allocation plan ([`MemoryPlan`]) over the SSA graph.
    /// Intermediate tensors whose liveness intervals `[def, last_use]` do not overlap share the
    /// same physical buffer slot.
    pub fn plan_memory(&self) -> MemoryPlan {
        let n = self.nodes.len();
        let live = self.live_set();
        let mut last_use: Vec<usize> = (0..n).collect();
        for node in &self.nodes {
            if !live.contains(&node.id) {
                continue;
            }
            for op_id in node.op.operands() {
                // Defensive (mirrors `live_set`): out-of-range ids in an
                // unvalidated hand-built graph are skipped instead of panicking.
                let Some(slot) = last_use.get_mut(op_id) else {
                    continue;
                };
                if node.id > *slot {
                    *slot = node.id;
                }
            }
        }
        // Outputs remain live until the end of execution
        for &out_id in &self.outputs {
            if out_id < n {
                last_use[out_id] = n;
            }
        }

        let mut slot_of: Vec<Option<usize>> = vec![None; n];
        let mut free_slots: Vec<usize> = Vec::new();
        let mut next_slot = 0usize;
        let mut reused_allocations = 0usize;
        let mut total_live_values = 0usize;

        let mut release_at: Vec<Vec<ValueId>> = vec![Vec::new(); n + 1];
        for (vid, &lu) in last_use.iter().enumerate() {
            if live.contains(&vid) {
                release_at[lu].push(vid);
            }
        }

        for step in 0..n {
            if !live.contains(&step) {
                continue;
            }
            total_live_values += 1;
            let slot = if let Some(reused) = free_slots.pop() {
                reused_allocations += 1;
                reused
            } else {
                let s = next_slot;
                next_slot += 1;
                s
            };
            slot_of[step] = Some(slot);

            for &expired_vid in &release_at[step] {
                if let Some(freed_slot) = slot_of[expired_vid] {
                    free_slots.push(freed_slot);
                }
            }
        }

        MemoryPlan {
            slot_of,
            total_live_values,
            peak_slots: next_slot,
            reused_allocations,
        }
    }

    /// Runs [`IrGraph::optimize`] followed by [`IrGraph::plan_memory`], returning an ahead-of-time
    /// [`CompiledGraph`] that executes using only `peak_slots` buffer slots.
    pub fn compile(mut self) -> Result<CompiledGraph> {
        let report = self.optimize()?;
        let memory_plan = self.plan_memory();
        Ok(CompiledGraph {
            graph: self,
            report,
            memory_plan,
        })
    }
}

/// Static linear-scan buffer allocation plan for an [`IrGraph`].
#[derive(Debug, Clone)]
pub struct MemoryPlan {
    pub slot_of: Vec<Option<usize>>,
    pub total_live_values: usize,
    pub peak_slots: usize,
    pub reused_allocations: usize,
}

impl MemoryPlan {
    /// Fraction of live SSA values that reused a previously freed physical slot.
    pub fn reuse_ratio(&self) -> f64 {
        if self.total_live_values == 0 {
            0.0
        } else {
            (self.reused_allocations as f64) / (self.total_live_values as f64)
        }
    }
}

/// Ahead-of-time optimized & memory-planned [`IrGraph`] executable with a fixed-size slot pool.
#[derive(Debug, Clone)]
pub struct CompiledGraph {
    pub graph: IrGraph,
    pub report: OptimizationReport,
    pub memory_plan: MemoryPlan,
}

impl CompiledGraph {
    /// Exports this compiled graph to an ONNX `ModelProto` byte buffer.
    pub fn to_onnx(&self, input_shapes: &[Vec<usize>], model_name: &str) -> Result<Vec<u8>> {
        self.graph.to_onnx(input_shapes, model_name)
    }
}

impl CompiledGraph {
    /// Lowers a pure elementwise [`IrGraph`] into a fused [`crate::jit::JitKernelBuilder`]
    /// (synthesizing WGSL on GPU or a single-pass CPU loop). Returns `None` if the graph
    /// contains non-elementwise ops (e.g. `Matmul`, reductions, shape ops).
    pub fn to_jit_kernel(&self) -> Option<crate::jit::JitKernelBuilder> {
        use crate::jit::{JitKernelBuilder, JitOp};
        if self.graph.outputs.is_empty() {
            return None;
        }
        let mut kb = JitKernelBuilder::new("compiled_subgraph");
        let mut map: HashMap<ValueId, usize> = HashMap::new();
        for (id, node) in self.graph.nodes.iter().enumerate() {
            let jit_id = match node.op {
                IrOp::Input { index } => {
                    if index != kb.input_count {
                        return None;
                    }
                    kb.add_input(format!("in_{index}"))
                }
                IrOp::Add(a, b) => kb.add_op(JitOp::Add, &[map[&a], map[&b]]),
                IrOp::Sub(a, b) => kb.add_op(JitOp::Sub, &[map[&a], map[&b]]),
                IrOp::Mul(a, b) => kb.add_op(JitOp::Mul, &[map[&a], map[&b]]),
                IrOp::Div(a, b) => kb.add_op(JitOp::Div, &[map[&a], map[&b]]),
                IrOp::FusedFma(a, b, c) => kb.add_op(JitOp::Fma, &[map[&a], map[&b], map[&c]]),
                IrOp::Relu(a) => kb.add_op(JitOp::Relu, &[map[&a]]),
                IrOp::Silu(a) => kb.add_op(JitOp::Silu, &[map[&a]]),
                IrOp::Gelu(a) => kb.add_op(JitOp::Gelu, &[map[&a]]),
                IrOp::Exp(a) => kb.add_op(JitOp::Exp, &[map[&a]]),
                IrOp::Neg(a) => kb.add_op(JitOp::Neg, &[map[&a]]),
                _ => return None,
            };
            map.insert(id, jit_id);
        }
        for &out in &self.graph.outputs {
            kb.set_output(*map.get(&out)?);
        }
        Some(kb)
    }

    pub fn execute(&self, inputs: &[Tensor]) -> Result<Vec<Tensor>> {
        if let Some(kb) = self.to_jit_kernel()
            && !inputs.is_empty()
            && inputs.iter().all(|t| {
                t.shape() == inputs[0].shape() && t.dtype() == inputs[0].dtype()
            })
        {
            let refs: Vec<&Tensor> = inputs.iter().collect();
            return kb.execute_all(&refs);
        }
        self.graph.execute(inputs)
    }
}

fn remap_op(op: &IrOp, mut f: impl FnMut(ValueId) -> ValueId) -> IrOp {
    match *op {
        IrOp::Input { index } => IrOp::Input { index },
        IrOp::ZeroLike { src } => IrOp::ZeroLike { src: f(src) },
        IrOp::OneLike { src } => IrOp::OneLike { src: f(src) },
        IrOp::Add(a, b) => IrOp::Add(f(a), f(b)),
        IrOp::Sub(a, b) => IrOp::Sub(f(a), f(b)),
        IrOp::Mul(a, b) => IrOp::Mul(f(a), f(b)),
        IrOp::Div(a, b) => IrOp::Div(f(a), f(b)),
        IrOp::Matmul(a, b) => IrOp::Matmul(f(a), f(b)),
        IrOp::Transpose2D(a) => IrOp::Transpose2D(f(a)),
        IrOp::Relu(a) => IrOp::Relu(f(a)),
        IrOp::Silu(a) => IrOp::Silu(f(a)),
        IrOp::Gelu(a) => IrOp::Gelu(f(a)),
        IrOp::Tanh(a) => IrOp::Tanh(f(a)),
        IrOp::Exp(a) => IrOp::Exp(f(a)),
        IrOp::Ln(a) => IrOp::Ln(f(a)),
        IrOp::Neg(a) => IrOp::Neg(f(a)),
        IrOp::Square(a) => IrOp::Square(f(a)),
        IrOp::SumAll(a) => IrOp::SumAll(f(a)),
        IrOp::MeanAll(a) => IrOp::MeanAll(f(a)),
        IrOp::FusedFma(a, b, c) => IrOp::FusedFma(f(a), f(b), f(c)),
        IrOp::FusedLinear { x, w, b } => IrOp::FusedLinear {
            x: f(x),
            w: f(w),
            b: f(b),
        },
        IrOp::FusedLinearRelu { x, w, b } => IrOp::FusedLinearRelu {
            x: f(x),
            w: f(w),
            b: f(b),
        },
        IrOp::FusedLinearSilu { x, w, b } => IrOp::FusedLinearSilu {
            x: f(x),
            w: f(w),
            b: f(b),
        },
        IrOp::FusedLinearGelu { x, w, b } => IrOp::FusedLinearGelu {
            x: f(x),
            w: f(w),
            b: f(b),
        },
    }
}

/// Dynamically traces a Rust closure `f` on `example_inputs` (`torch.fx.symbolic_trace`)
/// by recording the autograd DAG and lowering it into a symbolic [`IrGraph`].
pub fn trace_to_ir<F>(f: F, example_inputs: &[Tensor]) -> Result<IrGraph>
where
    F: FnOnce(&[Tensor]) -> Result<Tensor>,
{
    let mut graph = IrGraph::new();
    let mut id_to_ir: HashMap<usize, ValueId> = HashMap::new();
    let mut traced_inputs = Vec::with_capacity(example_inputs.len());

    for inp in example_inputs {
        let t = inp.detach().requires_grad_(true);
        let vid = graph.add_input();
        id_to_ir.insert(t.id(), vid);
        traced_inputs.push(t);
    }

    let out = enable_grad(|| f(&traced_inputs))?;

    /// Lowers one tensor DAG node after its parents (the iterative driver
    /// below guarantees every parent is already in `id_to_ir`).
    fn lower_one(
        t: &Tensor,
        graph: &mut IrGraph,
        id_to_ir: &HashMap<usize, ValueId>,
    ) -> Result<ValueId> {
        let op_name = t.op_name().ok_or_else(|| {
            Error::Msg(
                "trace_to_ir encountered an untracked leaf tensor; pass all leaf inputs via example_inputs"
                    .into(),
            )
        })?;
        let parents = t.op_inputs();
        let mut parent_ids = Vec::with_capacity(parents.len());
        for p in parents {
            parent_ids.push(*id_to_ir.get(&p.id()).ok_or_else(|| {
                Error::Msg(
                    "trace_to_ir: parent tensor was not lowered (cyclic autograd graph?)".into(),
                )
            })?);
        }

        Ok(match op_name {
            "broadcast_to" | "view_reshape" | "contiguous" => parent_ids[0],
            "add" => graph.push_op(IrOp::Add(parent_ids[0], parent_ids[1])),
            "sub" => graph.push_op(IrOp::Sub(parent_ids[0], parent_ids[1])),
            "mul" => graph.push_op(IrOp::Mul(parent_ids[0], parent_ids[1])),
            "div" => graph.push_op(IrOp::Div(parent_ids[0], parent_ids[1])),
            "matmul" => graph.push_op(IrOp::Matmul(parent_ids[0], parent_ids[1])),
            "transpose" => graph.push_op(IrOp::Transpose2D(parent_ids[0])),
            "relu" => graph.push_op(IrOp::Relu(parent_ids[0])),
            "silu" => graph.push_op(IrOp::Silu(parent_ids[0])),
            "gelu" => graph.push_op(IrOp::Gelu(parent_ids[0])),
            "tanh" => graph.push_op(IrOp::Tanh(parent_ids[0])),
            "exp" => graph.push_op(IrOp::Exp(parent_ids[0])),
            "ln" => graph.push_op(IrOp::Ln(parent_ids[0])),
            "neg" => graph.push_op(IrOp::Neg(parent_ids[0])),
            "square" => graph.push_op(IrOp::Square(parent_ids[0])),
            "sum_axes" => graph.push_op(IrOp::SumAll(parent_ids[0])),
            "mean_axes" => graph.push_op(IrOp::MeanAll(parent_ids[0])),
            other => {
                return Err(Error::Msg(format!(
                    "trace_to_ir: unsupported dynamic op '{other}'"
                )));
            }
        })
    }

    // Iterative post-order traversal with an explicit heap stack: lowering
    // recursed per DAG depth and overflowed the call stack on long chains
    // (e.g. 20k chained adds abort the process). The `visiting` set keeps
    // every tensor framed at most once, so traversal terminates even on a
    // hand-built cyclic graph (which then fails loudly in `lower_one`).
    let mut visiting: HashSet<usize> = HashSet::new();
    for id in id_to_ir.keys() {
        visiting.insert(*id);
    }
    let mut stack: Vec<(Tensor, bool)> = vec![(out.clone(), false)];
    while let Some((t, expanded)) = stack.pop() {
        if id_to_ir.contains_key(&t.id()) {
            continue;
        }
        if !expanded {
            if !visiting.insert(t.id()) {
                continue;
            }
            stack.push((t.clone(), true));
            for p in t.op_inputs() {
                if !id_to_ir.contains_key(&p.id()) {
                    stack.push((p.clone(), false));
                }
            }
            continue;
        }
        let vid = lower_one(&t, &mut graph, &id_to_ir)?;
        id_to_ir.insert(t.id(), vid);
    }
    let out_vid = *id_to_ir
        .get(&out.id())
        .ok_or_else(|| Error::Msg("trace_to_ir: output tensor was not lowered".into()))?;
    graph.set_outputs(vec![out_vid]);
    Ok(graph)
}

/// Traces `f` on `example_inputs` and runs all compiler optimization passes
/// (Algebraic Simplification, CSE, Operator Fusion, DCE, and Linear-Scan Memory Planning),
/// returning an ahead-of-time [`CompiledGraph`] (`torch.compile`).
pub fn jit_compile<F>(f: F, example_inputs: &[Tensor]) -> Result<CompiledGraph>
where
    F: FnOnce(&[Tensor]) -> Result<Tensor>,
{
    let graph = trace_to_ir(f, example_inputs)?;
    graph.compile()
}

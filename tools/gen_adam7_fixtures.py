"""Writes crates/oxideon-core/tests/png_adam7.rs: Adam7-interlaced PNGs made by pypng together with the pixels pypng itself reads back
(the reference the decoder must reproduce).

    pip install pypng
    python tools/gen_adam7_fixtures.py
"""
import io
import pathlib

import png

OUT = pathlib.Path(__file__).resolve().parent.parent / "crates/oxideon-core/tests/png_adam7.rs"


def pixels(w, h, planes, maxval, seed):
    state = seed
    rows = []
    for _ in range(h):
        row = []
        for _ in range(w * planes):
            state = (state * 1103515245 + 12345) & 0x7FFFFFFF
            row.append((state >> 8) % (maxval + 1))
        rows.append(row)
    return rows


def build(name, w, h, depth, kind):
    palette = None
    if kind == "gray":
        planes, kw = 1, dict(greyscale=True)
    elif kind == "rgb":
        planes, kw = 3, dict(greyscale=False)
    elif kind == "rgba":
        planes, kw = 4, dict(greyscale=False, alpha=True)
    elif kind == "graya":
        planes, kw = 2, dict(greyscale=True, alpha=True)
    else:  # palette
        planes = 1
        palette = [((i * 37) % 256, (i * 91) % 256, (i * 53) % 256) for i in range(1 << depth)]
        kw = dict(palette=palette)
    rows = pixels(w, h, planes, (1 << depth) - 1, w * 31 + h * 7 + depth)
    buf = io.BytesIO()
    png.Writer(w, h, bitdepth=depth, interlace=True, **kw).write(buf, rows)
    data = buf.getvalue()
    # what the decoder returns: 8-bit samples, low depths scaled to 0..255, 16-bit reduced to the high byte, palette -> RGB
    expected = []
    for row in rows:
        for v in row:
            if kind == "palette":
                continue
            expected.append(v >> 8 if depth == 16 else (v * 255 // ((1 << depth) - 1) if depth < 8 else v))
        if kind == "palette":
            for idx in row:
                expected.extend(palette[idx])
    channels = 3 if kind == "palette" else planes
    return name, data, expected, (w, h, channels)


cases = [
    build("gray8_5x7", 5, 7, 8, "gray"),
    build("rgb8_13x9", 13, 9, 8, "rgb"),
    build("rgba8_3x3", 3, 3, 8, "rgba"),
    build("graya8_6x5", 6, 5, 8, "graya"),
    build("gray16_9x5", 9, 5, 16, "gray"),
    build("rgb16_4x6", 4, 6, 16, "rgb"),
    build("gray1_11x6", 11, 6, 1, "gray"),
    build("gray2_7x7", 7, 7, 2, "gray"),
    build("gray4_9x9", 9, 9, 4, "gray"),
    build("palette4_6x6", 6, 6, 4, "palette"),
    build("palette1_17x3", 17, 3, 1, "palette"),
    build("gray8_1x1", 1, 1, 8, "gray"),
    build("gray8_2x2", 2, 2, 8, "gray"),
    build("rgb8_33x17", 33, 17, 8, "rgb"),
]

lines = [
    "// Generated by tools/gen_adam7_fixtures.py: Adam7-interlaced PNGs written by pypng with the pixels pypng reads back.",
    "use oxideon_core::image_codec::decode_png;",
    "",
    "#[allow(clippy::type_complexity)]",
    "const CASES: &[(&str, &[u8], &[u8], (usize, usize, usize))] = &[",
]
for name, data, expected, (w, h, c) in cases:
    lines.append(f'    ("{name}", &{list(data)}, &{expected}, ({w}, {h}, {c})),')
lines += [
    "];",
    "",
    "#[test]",
    "fn adam7_images_decode_to_the_reference_pixels() {",
    "    for (name, png, want, (w, h, c)) in CASES {",
    "        let (pixels, gw, gh, gc) = decode_png(png).unwrap_or_else(|e| panic!(\"{name}: {e}\"));",
    "        assert_eq!((gw, gh, gc), (*w, *h, *c), \"{name}: shape\");",
    "        assert_eq!(&pixels, want, \"{name}: pixels\");",
    "    }",
    "}",
    "",
    "#[test]",
    "fn truncated_adam7_data_is_an_error_not_a_panic() {",
    "    let (_, png, _, _) = &CASES[1];",
    "    for cut in (8..png.len()).step_by(7) {",
    "        let _ = decode_png(&png[..cut]);",
    "    }",
    "}",
    "",
]
OUT.write_text("\n".join(lines), encoding="utf-8")
print("wrote", OUT, len(cases), "cases")

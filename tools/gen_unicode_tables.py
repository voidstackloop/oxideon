"""Generates crates/oxideon-core/src/tokenizer/unicode_data.rs from Python's unicodedata (general categories,
canonical combining classes, canonical / compatibility decompositions, canonical composition pairs).

Run: py -3.11 tools/gen_unicode_tables.py
"""
import os, sys, unicodedata as ud

CATS = ["Cc", "Cf", "Cn", "Co", "Cs", "Ll", "Lm", "Lo", "Lt", "Lu", "Mc", "Me", "Mn", "Nd", "Nl", "No", "Pc", "Pd", "Pe",
        "Pf", "Pi", "Po", "Ps", "Sc", "Sk", "Sm", "So", "Zl", "Zp", "Zs"]
cid = {c: i for i, c in enumerate(CATS)}

def is_hangul(cp): return 0xAC00 <= cp <= 0xD7A3

out = []
out.append(f"//! GENERATED by tools/gen_unicode_tables.py from Python's unicodedata (Unicode {ud.unidata_version}). Do not edit.")
out.append("")
out.append("/// General category names, indexed by the ids used in [`CATEGORY_RUNS`].")
out.append("pub const CATEGORY_NAMES: [&str; %d] = [%s];" % (len(CATS), ", ".join(f'"{c}"' for c in CATS)))
out.append("")

# General category runs: (start, id); a run lasts until the next start.
runs = []; prev = None
for cp in range(0x110000):
    c = 4 if 0xD800 <= cp <= 0xDFFF else cid[ud.category(chr(cp))]
    if c != prev: runs.append((cp, c)); prev = c
out.append("pub const CATEGORY_RUNS: &[(u32, u8)] = &[")
line = "   "
for cp, c in runs:
    item = f" (0x{cp:X},{c}),"
    if len(line) + len(item) > 118: out.append(line); line = "   "
    line += item
out.append(line); out.append("];"); out.append("")

# Canonical combining class runs (non-zero only): (start, end, ccc)
ccc = []; cp = 0
while cp < 0x110000:
    v = ud.combining(chr(cp))
    if v:
        e = cp
        while e + 1 < 0x110000 and ud.combining(chr(e + 1)) == v: e += 1
        ccc.append((cp, e, v)); cp = e + 1
    else: cp += 1
out.append("pub const COMBINING_CLASS: &[(u32, u32, u8)] = &[")
line = "   "
for a, b, v in ccc:
    item = f" (0x{a:X},0x{b:X},{v}),"
    if len(line) + len(item) > 118: out.append(line); line = "   "
    line += item
out.append(line); out.append("];"); out.append("")

def full(cp, compat, cache):
    if cp in cache: return cache[cp]
    d = ud.decomposition(chr(cp))
    if not d or is_hangul(cp): r = [cp]
    else:
        parts = d.split()
        if parts[0].startswith("<"):
            if not compat: cache[cp] = [cp]; return [cp]
            parts = parts[1:]
        r = []
        for p in parts: r.extend(full(int(p, 16), compat, cache))
    cache[cp] = r; return r

for name, compat in (("CANON", False), ("COMPAT", True)):
    cache = {}; pool = []; idx = []
    for cp in range(0x110000):
        if ud.decomposition(chr(cp)) and not is_hangul(cp):
            f = full(cp, compat, cache)
            if f != [cp]:
                idx.append((cp, len(pool), len(f))); pool.extend(f)
    out.append(f"pub const DECOMP_{name}_INDEX: &[(u32, u32, u8)] = &[")
    line = "   "
    for cp, off, n in idx:
        item = f" (0x{cp:X},{off},{n}),"
        if len(line) + len(item) > 118: out.append(line); line = "   "
        line += item
    out.append(line); out.append("];")
    out.append(f"pub const DECOMP_{name}_POOL: &[u32] = &[")
    line = "   "
    for v in pool:
        item = f" 0x{v:X},"
        if len(line) + len(item) > 118: out.append(line); line = "   "
        line += item
    out.append(line); out.append("];"); out.append("")

# Composition pairs: two-element canonical decompositions that NFC recomposes.
pairs = []
for cp in range(0x110000):
    d = ud.decomposition(chr(cp))
    if d and not d.startswith("<") and not is_hangul(cp):
        parts = [int(p, 16) for p in d.split()]
        if len(parts) == 2 and ud.normalize("NFC", chr(parts[0]) + chr(parts[1])) == chr(cp):
            pairs.append((parts[0], parts[1], cp))
pairs.sort()
out.append("/// `(first, second, composite)` sorted by `(first, second)`.")
out.append("pub const COMPOSE_PAIRS: &[(u32, u32, u32)] = &[")
line = "   "
for a, b, c in pairs:
    item = f" (0x{a:X},0x{b:X},0x{c:X}),"
    if len(line) + len(item) > 118: out.append(line); line = "   "
    line += item
out.append(line); out.append("];")

dest = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "crates", "oxideon-core", "src", "tokenizer", "unicode_data.rs")
with open(dest, "w", newline="\n", encoding="utf-8") as f: f.write("\n".join(out) + "\n")
print("wrote", os.path.getsize(dest), "bytes;", len(runs), "category runs,", len(ccc), "ccc runs,", len(pairs), "pairs")

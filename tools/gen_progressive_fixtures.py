"""Writes crates/oxideon-core/tests/jpeg_progressive.rs: progressive and baseline JPEGs encoded by libjpeg (through Pillow) from the
same image, plus the pixels libjpeg decodes the baseline file to. Both files carry identical quantized coefficients, so the
progressive decode must equal the baseline decode exactly and both must stay close to libjpeg's own output.

    pip install pillow
    python tools/gen_progressive_fixtures.py
"""
import io
import math
import pathlib

from PIL import Image

OUT = pathlib.Path(__file__).resolve().parent.parent / "crates/oxideon-core/tests/jpeg_progressive.rs"


def make_image(w, h, mode, seed):
    img = Image.new("RGB", (w, h))
    px = img.load()
    state = seed
    for y in range(h):
        for x in range(w):
            state = (state * 1103515245 + 12345) & 0x7FFFFFFF
            noise = (state >> 10) % 24
            r = int(127 + 120 * math.sin(x * 0.21 + seed)) + noise
            g = int(127 + 120 * math.cos(y * 0.17)) - noise
            b = (x * 7 + y * 5) % 256 if (x // 6 + y // 5) % 2 else 40 + noise * 3  # hard edges
            px[x, y] = (max(0, min(255, r)), max(0, min(255, g)), max(0, min(255, b)))
    return img.convert(mode) if mode != "RGB" else img


def encode(img, progressive, quality, subsampling):
    buf = io.BytesIO()
    kw = dict(quality=quality, progressive=progressive, optimize=progressive)
    if img.mode == "RGB":
        kw["subsampling"] = subsampling
    img.save(buf, "JPEG", **kw)
    return buf.getvalue()


cases = []
for name, w, h, mode, quality, sub in [
    ("gray_37x23_q80", 37, 23, "L", 80, 0),
    ("gray_16x16_q95", 16, 16, "L", 95, 0),
    ("rgb444_24x24_q90", 24, 24, "RGB", 90, 0),
    ("rgb420_40x26_q75", 40, 26, "RGB", 75, 2),
    ("rgb422_33x17_q85", 33, 17, "RGB", 85, 1),
    ("rgb420_9x7_q60", 9, 7, "RGB", 60, 2),
]:
    img = make_image(w, h, mode, w * 3 + h)
    base = encode(img, False, quality, sub)
    prog = encode(img, True, quality, sub)
    assert base[:2] == b"\xff\xd8" and b"\xff\xc2" in prog and b"\xff\xc0" in base
    ref = Image.open(io.BytesIO(base))
    ref.load()
    ref_px = list(ref.tobytes())
    cases.append((name, base, prog, ref_px, (w, h, 1 if mode == "L" else 3)))

lines = [
    "// Generated by tools/gen_progressive_fixtures.py: libjpeg-encoded baseline and progressive twins of the same images.",
    "use oxideon_core::image_codec::decode_jpeg;",
    "",
    "#[allow(clippy::type_complexity)]",
    "const CASES: &[(&str, &[u8], &[u8], &[u8], (usize, usize, usize))] = &[",
]
for name, base, prog, ref_px, (w, h, c) in cases:
    lines.append(f'    ("{name}", &{list(base)}, &{list(prog)}, &{ref_px}, ({w}, {h}, {c})),')
lines += [
    "];",
    "",
    "#[test]",
    "fn progressive_equals_baseline_and_both_match_libjpeg() {",
    "    for (name, base, prog, libjpeg, (w, h, c)) in CASES {",
    "        let (b_px, bw, bh, bc) = decode_jpeg(base).unwrap_or_else(|e| panic!(\"{name} baseline: {e}\"));",
    "        let (p_px, pw, ph, pc) = decode_jpeg(prog).unwrap_or_else(|e| panic!(\"{name} progressive: {e}\"));",
    "        assert_eq!((bw, bh, bc), (*w, *h, *c), \"{name}\");",
    "        assert_eq!((pw, ph, pc), (*w, *h, *c), \"{name}\");",
    "        assert_eq!(p_px, b_px, \"{name}: the progressive and baseline files hold the same coefficients\");",
    "        let diffs: Vec<i32> = b_px.iter().zip(*libjpeg).map(|(a, b)| (*a as i32 - *b as i32).abs()).collect();",
    "        let max = *diffs.iter().max().unwrap();",
    "        let mean = diffs.iter().sum::<i32>() as f64 / diffs.len() as f64;",
    "        assert!(max <= 6 && mean < 0.8, \"{name}: differs from libjpeg by up to {max} (mean {mean:.3})\");",
    "    }",
    "}",
    "",
    "#[test]",
    "fn damaged_progressive_files_never_panic() {",
    "    let (_, _, prog, _, _) = CASES[3];",
    "    for len in 0..prog.len() {",
    "        let _ = std::panic::catch_unwind(|| decode_jpeg(&prog[..len])).unwrap_or_else(|_| panic!(\"panicked on a file cut to {len} bytes\"));",
    "    }",
    "    let mut seed = 99u32;",
    "    for _ in 0..600 {",
    "        let mut bad = prog.to_vec();",
    "        for _ in 0..3 {",
    "            seed = seed.wrapping_mul(1664525).wrapping_add(1013904223);",
    "            let i = (seed >> 8) as usize % bad.len();",
    "            seed = seed.wrapping_mul(1664525).wrapping_add(1013904223);",
    "            bad[i] = (seed >> 16) as u8;",
    "        }",
    "        assert!(std::panic::catch_unwind(|| decode_jpeg(&bad)).is_ok(), \"panicked on a corrupted progressive file\");",
    "    }",
    "}",
    "",
]
OUT.write_text("\n".join(lines), encoding="utf-8")
print("wrote", OUT, len(cases), "cases", OUT.stat().st_size // 1024, "KiB")
